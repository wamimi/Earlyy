import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { JsonRpcProvider, Contract, Interface, getAddress } from 'ethers';
process.loadEnvFile('.env.local');
const txHash=process.argv[2];
if(!/^0x[0-9a-fA-F]{64}$/.test(txHash??'')) throw new Error('Pass the actual confirmed deployment transaction hash.');
const rpc=new JsonRpcProvider(process.env.MONAD_RPC_URL);
if((await rpc.getNetwork()).chainId!==10143n) throw new Error('Monad testnet required.');
const [receipt,tx]=await Promise.all([rpc.getTransactionReceipt(txHash),rpc.getTransaction(txHash)]);
if(!receipt || receipt.status!==1 || !receipt.contractAddress || !tx || tx.to!==null) throw new Error('No successful contract-creation receipt.');
const admin=getAddress(process.env.MONAD_ESCROW_ADMIN);
const signer=getAddress(process.env.EARLY_ELIGIBILITY_SIGNER_ADDRESS);
if(getAddress(tx.from)!==admin) throw new Error('Unexpected deployment sender.');
const artifact=JSON.parse(readFileSync('contracts/monad/out/EarlyBenefitEscrow.sol/EarlyBenefitEscrow.json','utf8'));
const iface=new Interface(artifact.abi);
if(tx.data.toLowerCase()!==(artifact.bytecode.object+iface.encodeDeploy([admin,signer]).slice(2)).toLowerCase()) throw new Error('Creation bytecode/constructor mismatch.');
const c=new Contract(receipt.contractAddress,artifact.abi,rpc);
if(getAddress(await c.owner())!==admin || getAddress(await c.eligibilitySigner())!==signer) throw new Error('On-chain authority mismatch.');
const block=await rpc.getBlock(receipt.blockNumber);
if(block?.hash!==receipt.blockHash || await receipt.confirmations()<2) throw new Error('Wait for canonical confirmations.');
const manifest={chainId:10143,address:receipt.contractAddress,deploymentBlock:receipt.blockNumber,transactionHash:txHash,blockHash:receipt.blockHash,admin,eligibilitySigner:signer};
mkdirSync('contracts/monad/deployments',{recursive:true});writeFileSync('contracts/monad/deployments/10143.json',JSON.stringify(manifest,null,2)+'\n');
console.log(JSON.stringify(manifest,null,2));rpc.destroy();
