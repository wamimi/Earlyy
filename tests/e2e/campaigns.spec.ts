import { test, expect } from '@playwright/test';

test('campaign catalogue filters, details, and campaign brief work', async ({ page }, testInfo) => {
  await page.goto('/campaigns');
  await expect(page.getByRole('heading', { name: 'Your support opens doors.' })).toBeVisible();
  await expect(page.locator('.cp-opportunity')).toHaveCount(3);
  await page.getByRole('button', { name: 'Brands', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Brands', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(page.getByRole('heading', { name: 'First in. First access.' })).toBeVisible();
  await page.getByRole('button', { name: 'Explore First in. First access.' }).click();
  const detail = page.getByRole('dialog', { name: 'First in. First access.' });
  await expect(detail).toBeVisible();
  await expect(detail.getByText('Public campaigns haven’t launched yet.', { exact: false })).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(detail).not.toBeVisible();
  await expect(page.getByRole('button', { name: 'Explore First in. First access.' })).toBeFocused();
  await page.getByRole('button', { name: 'Communities', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Your people. Your place.' })).toBeVisible();
  await page.getByRole('button', { name: 'Music', exact: true }).click();
  await page.getByRole('button', { name: 'Create a campaign', exact: false }).first().click();
  const planner = page.getByRole('dialog', { name: 'Plan your campaign.' });
  await expect(planner).toBeVisible();
  await planner.getByLabel('Your artist, brand, or community').fill('First listeners');
  await planner.getByLabel('What support qualifies?').fill('Listened before the first album release');
  await planner.getByLabel('What will you offer?').fill('A reserved concert ticket allocation');
  const downloadPromise = page.waitForEvent('download');
  await planner.getByRole('button', { name: 'Download campaign brief' }).click();
  expect((await downloadPromise).suggestedFilename()).toBe('early-campaign-brief.md');
  await expect(planner.getByRole('status')).toHaveText('Your campaign brief is ready.');
  await page.keyboard.press('Escape');
  await page.evaluate(async () => { await Promise.all(Array.from(document.images).map(image => image.decode().catch(() => {}))); });
  expect(await page.locator('.cp-hero-background').evaluate((el: HTMLImageElement) => el.naturalWidth > 0)).toBe(true);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(await page.locator('main').innerText()).not.toContain('—');
  await page.evaluate(() => (document.activeElement as HTMLElement)?.blur());
  await page.addStyleTag({ content: "nextjs-portal { display: none !important; }" });
  await page.screenshot({ path: `/tmp/early-campaigns-${testInfo.project.name}-full.png`, fullPage: true });
  await page.setViewportSize({ width: 820, height: 1180 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});
